function table(s,headers,rows,top=218,widths=[390,778],height=344,fontSize=24){
 const all=[headers,...rows];
 const t=s.tables.add({rows:all.length,columns:headers.length,left:56,top,width:1168,height,values:all,columnWidths:widths});
 t.borders.assign({fill:'#FFFFFF',width:3,style:'solid'});
 t.cells.block({row:0,column:0,rowCount:all.length,columnCount:headers.length}).assign({
  textStyle:{typeface:font,fontSize,color:C.body},margins:{left:18,right:18,top:12,bottom:10},anchor:'center'
 });
 for(let r=0;r<all.length;r++){
  const range=t.cells.block({row:r,column:0,rowCount:1,columnCount:headers.length});
  range.fill=r===0?C.navy:(r%2?C.light:'#FAFAFD');
  range.textStyle.color=r===0?C.white:C.body;
  range.textStyle.bold=r===0;
  t.rows[r].height=height/all.length;
 }
 return t;
}

