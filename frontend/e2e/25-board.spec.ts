  const card = page.getByTestId('card-SR-2026-0017')
  await expect(card).toContainText('просрочена')
  await expect(card).toContainText('Критический')
  await expect(card).toContainText('Отключение вводного шкафа КТП-160')
  await expect(card).toContainText('ТОО «Демо Логистик»')
  await expect(card).toHaveClass(/pulse/)
  const c8 = page.getByTestId('card-SR-2026-0008')
  await expect(c8).toContainText('Просрочено на 1 ч 30 мин')
  await expect(c8).toContainText('Инженер Демо-2')
  await expect(c8).toContainText('☑')
  await expect(page.getByTestId('col-in_progress').getByTestId('card-SR-2026-0009')).toContainText(/Осталось/)
  await page.screenshot({ path: 'artifacts/screens/board-kanban.png' })

  // поиск с автодополнением + фильтры
  await page.getByLabel('Поиск заявок').fill('0017')
  await expect(page.getByRole('option', { name: /SR-2026-0017/ })).toBeVisible()
  await page.getByLabel('Поиск заявок').fill('Агро')
  await expect(page.getByTestId('card-SR-2026-0017')).toHaveCount(0)
  await expect(page.getByTestId('card-SR-2026-0003')).toBeVisible()
  await page.getByRole('button', { name: /Приоритеты/ }).click()
  await page.getByRole('option', { name: /Критический/ }).or(page.getByLabel('Критический')).first().check()
