test('BOARD-03 перетаскивание и обновление в реальном времени у диспетчера', async ({ browser }) => {
  const d = await as(browser, 'dispatcher', { viewport: { width: 1600, height: 900 } })
  const e = await as(browser, 'eng1', { viewport: { width: 1600, height: 900 } })
  await d.page.goto('/board')
  await e.page.goto('/board')
  await expect(d.page.locator('.live.live')).toBeVisible({ timeout: 15000 })
  // диспетчер: SR-0016 (Новая) → «Принята / Назначена» открывает назначение
  await drag(d.page, 'SR-2026-0016', 'assigned')
  const dlg = d.page.getByRole('dialog')
  await expect(dlg.getByRole('heading', { name: 'Назначить инженера' })).toBeVisible()
  await expect(dlg.getByLabel('Инженер', { exact: true }).locator('option')).toHaveCount(3)
  await dlg.getByLabel('Инженер', { exact: true }).selectOption({ label: /Демо-1/ as any }).catch(async () => {
    await dlg.getByLabel('Инженер', { exact: true }).selectOption({ index: 1 })
  })
  await dlg.getByRole('button', { name: 'Назначить инженера' }).click()
  await expect(d.page.getByTestId('col-assigned').getByTestId('card-SR-2026-0016')).toBeVisible()
  // недопустимое перемещение: диспетчер не может «начать» работу — сообщение и карточка остаётся
  await drag(d.page, 'SR-2026-0014', 'in_progress')
  await expect(d.page.getByText(/Начать работу может только назначенный инженер/)).toBeVisible()
  await expect(d.page.getByTestId('col-assigned').getByTestId('card-SR-2026-0014')).toBeVisible()
  // инженер перетаскивает SR-0014 (назначена ему) в «В работе» — у диспетчера карточка переезжает сама
  await expect(e.page.getByTestId('col-assigned').getByTestId('card-SR-2026-0014')).toBeVisible()
  await drag(e.page, 'SR-2026-0014', 'in_progress')
  await expect(e.page.getByTestId('col-in_progress').getByTestId('card-SR-2026-0014')).toBeVisible()
  await expect(d.page.getByTestId('col-in_progress').getByTestId('card-SR-2026-0014')).toBeVisible({ timeout: 10000 })
  await expect(d.page.getByTestId('col-assigned').getByTestId('card-SR-2026-0014')).toHaveCount(0)
  // пауза через перетаскивание: диалог с причиной
  await drag(d.page, 'SR-2026-0014', 'waiting')
  const p = d.page.getByRole('dialog')
  await expect(p.getByRole('heading', { name: 'Приостановить' })).toBeVisible()
  await p.getByRole('button', { name: 'Отмена' }).click()
  await d.page.screenshot({ path: 'artifacts/screens/board-after-drag.png' })
  for (const x of [d, e]) await x.ctx.close()
})

