/** Перетаскивание карточки мышью (dnd-kit требует пошагового движения указателя) */
async function drag(page: Page, from: string, toCol: string) {
  const card = page.getByTestId(`card-${from}`)
  const col = page.getByTestId(`col-${toCol}`)
  await card.scrollIntoViewIfNeeded()
  const a = (await card.boundingBox())!
  const b = (await col.boundingBox())!
  await page.mouse.move(a.x + a.width / 2, a.y + 30)
  await page.mouse.down()
  await page.mouse.move(a.x + a.width / 2 + 12, a.y + 40, { steps: 3 })
  await page.mouse.move(b.x + b.width / 2, b.y + 140, { steps: 12 })
  await page.mouse.up()
}

